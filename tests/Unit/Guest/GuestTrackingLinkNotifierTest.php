<?php

namespace Tests\Unit\Guest;

use App\Services\Guest\GuestOrderTokenService;
use App\Services\Guest\GuestTrackingLinkNotifier;
use App\Services\Notifications\SMSService;
use Illuminate\Mail\Transport\ArrayTransport;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Mail;
use Marvel\Database\Models\Order;
use Mockery;
use Mockery\MockInterface;
use Tests\TestCase;

/**
 * Delivery-path tests for the guest tracking-link notifier.
 *
 * Seams (all existing, zero new):
 *  - the notifier's public API with SMS, log, and mail fakes;
 *  - the REAL array mailer transport (MAIL_MAILER=array) for raw email
 *    content — MailFake::raw() is a no-op, so Mail::fake() cannot prove the
 *    email channel;
 *  - the framework terminating phase: notifyAfterResponse() registers the
 *    delivery as an app()->terminating() callback, exactly what the
 *    production HTTP kernel executes through Application::terminate() after
 *    the response is sent. The test runner never terminates, so tests call
 *    $this->app->terminate() to run the scheduled work deterministically.
 *
 * Every fixture order carries a REAL cancellation token (generated by the
 * production token service, stored as its keyed hash) so the
 * "tracking-token-only" claim is a falsifiable negative: the SMS body,
 * email body, and log contexts must contain neither that token nor any
 * cancellation link.
 */
class GuestTrackingLinkNotifierTest extends TestCase
{
    private const TRACKING_TOKEN = 'trk_token';

    private string $rawCancellationToken = '';
    private string $cancellationTokenHash = '';

    private function order(array $attrs = []): Order
    {
        $tokens = app(GuestOrderTokenService::class);

        // Real cancellation-token fixture: a production-format token the test
        // holds in the raw, plus its keyed hash on the order as issued.
        $this->rawCancellationToken = $tokens->generateToken();
        $this->cancellationTokenHash = $tokens->hash($this->rawCancellationToken);

        return (new Order())->forceFill(array_merge([
            'id' => 10,
            'order_number' => 'MEEM-10',
            'guest_id' => 5,
            'user_id' => null,
            'user_phone' => '01012345678',
            'user_email' => null,
            'guest_cancellation_token_hash' => $this->cancellationTokenHash,
        ], $attrs));
    }

    public function test_url_targets_frontend_with_encoded_token(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com/', 'path' => 'track-order']]);

        $url = app(GuestTrackingLinkNotifier::class)->trackingUrl('abc_DEF-123');

        $this->assertSame('https://meem.com/track-order?token=abc_DEF-123', $url);
    }

    public function test_sms_delivers_the_tracking_link_only_with_a_real_cancellation_token_on_the_order(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com', 'path' => '/track-order']]);

        $sent = [];
        $sms = $this->smsFake($sent);

        (new GuestTrackingLinkNotifier($sms))->notify($this->order(), self::TRACKING_TOKEN, 'en');

        $this->assertCount(1, $sent, 'Exactly one SMS attempt per notify()');
        $this->assertSame('+201012345678', $sent[0]['to']);
        $this->assertStringContainsString('https://meem.com/track-order?token=' . self::TRACKING_TOKEN, $sent[0]['message']);
        $this->assertStringContainsString('MEEM-10', $sent[0]['message']);
        $this->assertTrackingOnly($sent[0]['message'], 'The tracking SMS');
        $this->assertSame(10, $sent[0]['metadata']['order_id']);
        $this->assertSame('guest_tracking_link', $sent[0]['metadata']['type']);
    }

    public function test_email_is_sent_to_the_order_address_with_the_tracking_link(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com', 'path' => '/track-order']]);

        $sent = [];
        $sms = $this->smsFake($sent);

        (new GuestTrackingLinkNotifier($sms))
            ->notify($this->order(['user_email' => 'guest.buyer@example.test']), self::TRACKING_TOKEN, 'en');

        $transport = $this->mailTransport();
        $this->assertCount(1, $transport->messages(), 'Exactly one email per notify()');

        $email = $transport->messages()->last()->getOriginalMessage();
        $this->assertSame('guest.buyer@example.test', $email->getTo()[0]->getAddress(), 'Mail goes to the order address');
        $this->assertStringContainsString('MEEM-10', (string) $email->getSubject());
        $this->assertStringContainsString('https://meem.com/track-order?token=' . self::TRACKING_TOKEN, (string) $email->getTextBody());
        $this->assertTrackingOnly((string) $email->getTextBody(), 'The tracking email');
    }

    public function test_email_still_sends_when_sms_throws(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com', 'path' => '/track-order']]);

        $sent = [];
        $sms = $this->smsFake($sent, 1, new \RuntimeException('gateway down'));

        (new GuestTrackingLinkNotifier($sms))
            ->notify($this->order(['user_email' => 'guest.buyer@example.test']), self::TRACKING_TOKEN, 'en');

        $this->assertCount(1, $sent, 'Exactly one isolated SMS attempt');

        $transport = $this->mailTransport();
        $this->assertCount(1, $transport->messages(), 'Channel isolation: the email must still send when the SMS throws');

        $email = $transport->messages()->last()->getOriginalMessage();
        $this->assertSame('guest.buyer@example.test', $email->getTo()[0]->getAddress());
        $this->assertStringContainsString('https://meem.com/track-order?token=' . self::TRACKING_TOKEN, (string) $email->getTextBody());
        $this->assertTrackingOnly((string) $email->getTextBody(), 'The email sent despite the SMS failure');
    }

    public function test_sms_failure_is_logged_without_credentials_or_a_cancellation_link(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com', 'path' => '/track-order']]);

        $log = $this->recordingLog();
        $sent = [];
        $sms = $this->smsFake($sent, 1, new \RuntimeException('gateway down'));

        (new GuestTrackingLinkNotifier($sms))->notify($this->order(), self::TRACKING_TOKEN, 'en');

        $warnings = array_values(array_filter(
            $log->lines,
            fn (array $line): bool => $line['level'] === 'warning'
        ));

        $this->assertCount(1, $warnings, 'The SMS failure must be observable as exactly one warning');
        $this->assertSame('Guest tracking link SMS failed', $warnings[0]['message']);
        $this->assertSame(10, $warnings[0]['context']['order_id']);
        $this->assertSame('gateway down', $warnings[0]['context']['error']);

        // No log line anywhere may carry the cancellation token (raw or hash),
        // the tracking token, or the recipient phone.
        $serialized = (string) json_encode($log->lines);
        foreach ([
            $this->rawCancellationToken,
            $this->cancellationTokenHash,
            self::TRACKING_TOKEN,
            '+201012345678',
            '01012345678',
        ] as $secret) {
            $this->assertStringNotContainsString($secret, $serialized, "The notifier log leaked '{$secret}'");
        }
    }

    public function test_null_tracking_token_skips_delivery(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'https://meem.com', 'path' => '/track-order']]);

        $sent = [];
        $sms = $this->smsFake($sent, 0);

        (new GuestTrackingLinkNotifier($sms))
            ->notifyAfterResponse($this->order(['user_email' => 'guest.buyer@example.test']), null);

        $this->app->terminate();

        $this->assertSame([], $sent, 'A missing token must skip the SMS channel');
        $this->assertCount(0, $this->mailTransport()->messages(), 'A missing token must skip the email channel');
    }

    public function test_registered_user_order_is_not_notified(): void
    {
        $sent = [];
        $sms = $this->smsFake($sent, 0);

        (new GuestTrackingLinkNotifier($sms))
            ->notifyAfterResponse($this->order(['user_id' => 3, 'user_email' => 'guest.buyer@example.test']), self::TRACKING_TOKEN);

        $this->app->terminate();

        $this->assertSame([], $sent, 'Registered-user orders must not receive the guest tracking SMS');
        $this->assertCount(0, $this->mailTransport()->messages(), 'Registered-user orders must not receive the guest tracking email');
    }

    public function test_disabled_by_config(): void
    {
        config(['guest_checkout.tracking_link.enabled' => false]);

        $sent = [];
        $sms = $this->smsFake($sent, 0);

        (new GuestTrackingLinkNotifier($sms))
            ->notifyAfterResponse($this->order(['user_email' => 'guest.buyer@example.test']), self::TRACKING_TOKEN);

        $this->app->terminate();

        $this->assertSame([], $sent, 'The disabled toggle must schedule no SMS delivery');
        $this->assertCount(0, $this->mailTransport()->messages(), 'The disabled toggle must schedule no email delivery');
    }

    public function test_tracking_link_translation_keys_exist_in_en_and_ar(): void
    {
        foreach (['en', 'ar'] as $locale) {
            $group = trans('guest_checkout', [], $locale);

            foreach (['tracking_sms', 'tracking_email_subject', 'tracking_email_body'] as $key) {
                $this->assertArrayHasKey($key, $group, "[{$locale}] missing the tracking-link key {$key}");
                $this->assertIsString($group[$key], "[{$locale}] {$key} must be a string");
                $this->assertNotSame('', $group[$key], "[{$locale}] {$key} must not be empty");
            }

            // The delivery contract: the notifier replaces :order_number and :url.
            $bodies = $group['tracking_sms'] . $group['tracking_email_body'];
            $this->assertStringContainsString(':order_number', $bodies, "[{$locale}] tracking bodies must carry :order_number");
            $this->assertStringContainsString(':url', $bodies, "[{$locale}] tracking bodies must carry :url");
            $this->assertStringContainsString(':order_number', $group['tracking_email_subject'], "[{$locale}] email subject must carry :order_number");
        }
    }

    /**
     * SMSService fake: real-like phone formatting/validation and a send()
     * that records every attempt into $sent (by reference). $times === 0
     * makes any delivery attempt fail the test immediately.
     */
    private function smsFake(array &$sent, int $times = 1, ?\Throwable $thrownOnSend = null): MockInterface
    {
        $sent = [];

        $sms = Mockery::mock(SMSService::class);
        $sms->shouldReceive('formatPhone')->andReturn('+201012345678');
        $sms->shouldReceive('validatePhone')->andReturn(true);

        $expectation = $sms->shouldReceive('send')->andReturnUsing(
            function (string $to, string $message, array $metadata = []) use (&$sent, $thrownOnSend) {
                $sent[] = ['to' => $to, 'message' => $message, 'metadata' => $metadata];

                if ($thrownOnSend !== null) {
                    throw $thrownOnSend;
                }

                return ['success' => true, 'message_id' => 'test_simulated', 'response' => ['status' => 'simulated']];
            }
        );

        $times === 0 ? $expectation->never() : $expectation->times($times);

        return $sms;
    }

    /**
     * The real array mailer transport (MAIL_MAILER=array in the test config).
     */
    private function mailTransport(): ArrayTransport
    {
        $transport = app('mailer')->getSymfonyTransport();

        $this->assertInstanceOf(ArrayTransport::class, $transport, 'MAIL_MAILER must be the array transport for these tests');

        return $transport;
    }

    /**
     * A recording log fake swapped over the Log facade: captures every line
     * (level, message, context) so negative assertions scan ALL log output,
     * not only the levels the notifier is expected to use.
     */
    private function recordingLog(): object
    {
        $recorder = new class {
            public array $lines = [];

            public function __call(string $method, array $arguments)
            {
                $this->lines[] = [
                    'level' => $method,
                    'message' => $arguments[0] ?? null,
                    'context' => $arguments[1] ?? [],
                ];

                return null;
            }
        };

        Log::swap($recorder);

        return $recorder;
    }

    /**
     * The security claim "tracking-token-only": the message must carry the
     * tracking link but never the cancellation token in any form (raw or
     * hash) — and therefore never a cancellation link.
     */
    private function assertTrackingOnly(string $body, string $label): void
    {
        $this->assertStringNotContainsString($this->rawCancellationToken, $body, "{$label} leaked the raw cancellation token");
        $this->assertStringNotContainsString($this->cancellationTokenHash, $body, "{$label} leaked the cancellation token hash");
    }

    /**
     * Minimal log fake (this framework snapshot ships no Log::fake): captures
     * warnings on the container 'log' binding the Log facade resolves.
     */
    private function fakeLog(): object
    {
        $fake = new class {
            /** @var array<int, array{message: string, context: array<string, mixed>}> */
            public array $warnings = [];

            public function warning(string $message, array $context = []): void
            {
                $this->warnings[] = ['message' => $message, 'context' => $context];
            }
        };

        Log::swap($fake);

        return $fake;
    }

    public function test_production_skips_delivery_for_non_https_base_url(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'http://meem.com', 'path' => '/track-order']]);
        $log = $this->fakeLog();
        Mail::fake();
        $sms = Mockery::mock(SMSService::class);
        $sms->shouldNotReceive('send');

        try {
            app()['env'] = 'production';
            (new GuestTrackingLinkNotifier($sms))->notify(
                $this->order(['user_email' => 'guest@example.com']),
                'trk_token',
                'en'
            );
        } finally {
            app()['env'] = 'testing';
        }

        $this->assertCount(1, $log->warnings);
        $this->assertStringContainsString('not a valid https', $log->warnings[0]['message']);
        $this->assertSame(10, $log->warnings[0]['context']['order_id']);
        // The raw token must never reach the log, message or context.
        $this->assertStringNotContainsString('trk_token', json_encode($log->warnings, JSON_THROW_ON_ERROR));
        Mail::assertNothingSent();
    }

    public function test_production_skips_delivery_for_malformed_base_url(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'meem.com/track', 'path' => '/track-order']]);
        $log = $this->fakeLog();
        Mail::fake();
        $sms = Mockery::mock(SMSService::class);
        $sms->shouldNotReceive('send');

        try {
            app()['env'] = 'production';
            (new GuestTrackingLinkNotifier($sms))->notify($this->order(), 'trk_token', 'en');
        } finally {
            app()['env'] = 'testing';
        }

        $this->assertCount(1, $log->warnings);
        $this->assertStringContainsString('not a valid https', $log->warnings[0]['message']);
        $this->assertStringNotContainsString('trk_token', json_encode($log->warnings, JSON_THROW_ON_ERROR));
    }

    public function test_non_production_keeps_delivering_with_http_base_url(): void
    {
        config(['guest_checkout.tracking_link' => ['enabled' => true, 'base_url' => 'http://localhost', 'path' => '/track-order']]);
        $this->fakeLog();
        $sms = Mockery::mock(SMSService::class);
        $sms->shouldReceive('formatPhone')->andReturn('+201012345678');
        $sms->shouldReceive('validatePhone')->andReturn(true);
        $sms->shouldReceive('send')->once()->withArgs(function ($to, $message) {
            return $to === '+201012345678'
                && str_contains($message, 'http://localhost/track-order?token=trk_token');
        })->andReturn(['success' => true]);

        (new GuestTrackingLinkNotifier($sms))->notify($this->order(), 'trk_token', 'en');
    }
}
