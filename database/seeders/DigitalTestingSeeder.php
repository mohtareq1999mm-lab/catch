<?php

namespace Database\Seeders;

use App\Enums\DigitalAssetType;
use App\Models\DigitalAsset;
use App\Models\DigitalEntitlement;
use App\Services\Digital\DigitalAssetService;
use App\Services\Digital\DigitalEntitlementService;
use App\Services\Digital\DigitalFulfillmentService;
use Illuminate\Database\Seeder;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Hash;
use Marvel\Database\Models\Order;
use Marvel\Database\Models\OrderProduct;
use Marvel\Database\Models\Product;
use Marvel\Database\Models\User;
use Marvel\Enums\ItemType;
use Marvel\Enums\Permission;
use Marvel\Enums\ProductType;
use Spatie\Permission\Models\Permission as SpatiePermission;

/**
 * Local-only deterministic seeder for the Digital Assets & Entitlements
 * testing kit. Read the companion guide BEFORE running:
 * docs/testing/digital-assets-entitlements-seeding.md
 *
 * Safety contract (enforced in code, not just docs):
 * - Refuses to run when APP_ENV is production.
 * - NEVER truncates, resets, or wipes any table.
 * - Every record is created via firstOrCreate / existence checks on a
 *   UNIQUE key (email, slug, uuid anchor, order number), so reruns only
 *   top up what is missing instead of duplicating.
 * - Synthetic data only: fake license keys are prefixed TEST-ONLY, the
 *   test PDF is generated bytes, the URL asset points at example.com.
 * - Real files land on the configured `private` disk only.
 * - Plaintext secrets are never printed to the console.
 */
class DigitalTestingSeeder extends Seeder
{
    public const ADMIN_EMAIL = 'digital.admin@example.test';

    public const CUSTOMER_EMAIL = 'digital.customer@example.test';

    public const NOPERM_EMAIL = 'digital.noperm@example.test';

    public const DIGITAL_PRODUCT_SLUG = 'digital-test-ebook';

    public const PHYSICAL_PRODUCT_SLUG = 'digital-test-physical-gadget';

    public const ORDER_NUMBER = 'ORD-DIGITAL-TEST-001';

    /** @var array<string, string> uuid anchors printed for Postman */
    public array $anchors = [];

    public function run(): void
    {
        if (app()->environment('production')) {
            $this->command->error('DigitalTestingSeeder refuses to run in production.');

            return;
        }

        $this->seedPermissions();
        $admin = $this->seedAdmin();
        $this->seedPlainUsers();
        $digitalProduct = $this->seedDigitalProduct();
        $this->seedPhysicalProduct();
        $this->seedAssets($digitalProduct);
        $this->seedOrderAndEntitlements($digitalProduct);

        $this->printSummary($admin);
    }

    private function seedPermissions(): void
    {
        foreach ([
            Permission::VIEW_PRODUCTS,
            Permission::CREATE_PRODUCT,
            Permission::UPDATE_PRODUCT,
            Permission::DELETE_PRODUCT,
            Permission::MANAGE_DIGITAL_LICENSES,
            Permission::VIEW_ORDERS,
            Permission::MANAGE_DIGITAL_ACCESS,
        ] as $name) {
            SpatiePermission::firstOrCreate(['name' => $name, 'guard_name' => 'api']);
        }
    }

    private function seedAdmin(): User
    {
        $email = env('DIGITAL_TEST_ADMIN_EMAIL', self::ADMIN_EMAIL);
        $password = env('DIGITAL_TEST_ADMIN_PASSWORD', 'Test1234!LocalOnly');

        $admin = User::firstOrCreate(
            ['email' => $email],
            [
                'name' => 'Digital Test Admin',
                'email_verified_at' => now(),
                'password' => Hash::make($password),
                'is_active' => true,
                'type' => 'admin',
            ]
        );

        $admin->givePermissionTo([
            Permission::VIEW_PRODUCTS,
            Permission::CREATE_PRODUCT,
            Permission::UPDATE_PRODUCT,
            Permission::DELETE_PRODUCT,
            Permission::MANAGE_DIGITAL_LICENSES,
            Permission::VIEW_ORDERS,
            Permission::MANAGE_DIGITAL_ACCESS,
        ]);

        return $admin;
    }

    private function seedPlainUsers(): void
    {
        // Customer: owns the seeded order + entitlements (never admin).
        User::firstOrCreate(
            ['email' => self::CUSTOMER_EMAIL],
            [
                'name' => 'Digital Test Customer',
                'email_verified_at' => now(),
                'password' => Hash::make('Test1234!LocalOnly'),
                'is_active' => true,
                'type' => 'customer',
            ]
        );

        // Non-privileged admin: valid login, zero permissions (negative tests).
        User::firstOrCreate(
            ['email' => self::NOPERM_EMAIL],
            [
                'name' => 'Digital No-Perm Admin',
                'email_verified_at' => now(),
                'password' => Hash::make('Test1234!LocalOnly'),
                'is_active' => true,
                'type' => 'admin',
            ]
        );
    }

    private function seedDigitalProduct(): Product
    {
        return Product::firstOrCreate(
            ['slug' => self::DIGITAL_PRODUCT_SLUG],
            [
                'name' => ['en' => 'Digital Test E-book'],
                'description' => ['en' => 'Synthetic digital product for local API testing.'],
                'price' => 25.00,
                'product_type' => ProductType::SIMPLE,
                'item_type' => ItemType::DIGITAL,
                'status' => 1,
                'in_stock' => true,
                'stock_quantity' => 100,
            ]
        );
    }

    private function seedPhysicalProduct(): Product
    {
        return Product::firstOrCreate(
            ['slug' => self::PHYSICAL_PRODUCT_SLUG],
            [
                'name' => ['en' => 'Physical Test Gadget'],
                'description' => ['en' => 'Synthetic physical product (asset creation must reject it).'],
                'price' => 10.00,
                'product_type' => ProductType::SIMPLE,
                'item_type' => ItemType::PHYSICAL,
                'status' => 1,
                'in_stock' => true,
                'stock_quantity' => 50,
            ]
        );
    }

    private function seedAssets(Product $product): void
    {
        $service = app(DigitalAssetService::class);

        if (!DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::FILE->value)->exists()) {
            $service->store($product, $this->syntheticPdf(), ['original_name' => 'test-manual']);
        }

        if (!DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::URL->value)->exists()) {
            $service->createUrl($product, [
                'external_url' => 'https://example.com/test-resource',
                'original_name' => 'test-external-link',
            ]);
        }

        $license = DigitalAsset::where('product_id', $product->id)
            ->where('type', DigitalAssetType::LICENSE->value)
            ->first();

        if (!$license) {
            $license = $service->createLicense($product, ['original_name' => 'test-license-pool']);
        }

        if (\App\Models\DigitalLicenseKey::where('asset_id', $license->id)->count() === 0) {
            $service->addLicenseKeys($license, [
                'TEST-ONLY-AAAA-0001',
                'TEST-ONLY-BBBB-0002',
                'TEST-ONLY-CCCC-0003',
                'TEST-ONLY-DDDD-0004',
                'TEST-ONLY-EEEE-0005',
            ]);
        }

        if (!DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::ACCESS->value)->exists()) {
            $service->createAccess($product, [
                'original_name' => 'test-access-credential',
                'secret' => 'TEST-ONLY-SECRET-do-not-use-in-production',
            ]);
        }

        $this->anchors['file_asset_uuid'] = (string) DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::FILE->value)->value('uuid');
        $this->anchors['url_asset_uuid'] = (string) DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::URL->value)->value('uuid');
        $this->anchors['license_asset_uuid'] = (string) $license->uuid;
        $this->anchors['access_asset_uuid'] = (string) DigitalAsset::where('product_id', $product->id)->where('type', DigitalAssetType::ACCESS->value)->value('uuid');
    }

    private function seedOrderAndEntitlements(Product $product): void
    {
        $customer = User::where('email', self::CUSTOMER_EMAIL)->firstOrFail();

        $order = Order::firstOrCreate(
            ['order_number' => self::ORDER_NUMBER],
            [
                'user_id' => $customer->id,
                'status' => 'pending',
                'payment_status' => 'payment-success',
                'fulfillment_status' => 'pending',
                'payment_method' => 'online',
                'total_price' => 25.00,
            ]
        );

        $item = OrderProduct::firstOrCreate(
            ['order_id' => $order->id, 'product_id' => $product->id],
            [
                'product_name' => 'Digital Test E-book',
                'product_quantity' => 1,
                'product_price' => 25.00,
                'product_total_price' => 25.00,
                'item_type' => ItemType::DIGITAL,
            ]
        );

        // Two extra REAL order lines (same order/product) so the expired and
        // revoked fixtures also satisfy the order_products FK and go through
        // the real fulfillment pathway like line 1.
        $line2 = OrderProduct::firstOrCreate(
            ['order_id' => $order->id, 'product_name' => 'Digital Test E-book (expiry fixture)'],
            [
                'product_id' => $product->id,
                'product_quantity' => 1,
                'product_price' => 25.00,
                'product_total_price' => 25.00,
                'item_type' => ItemType::DIGITAL,
            ]
        );

        $line3 = OrderProduct::firstOrCreate(
            ['order_id' => $order->id, 'product_name' => 'Digital Test E-book (revocation fixture)'],
            [
                'product_id' => $product->id,
                'product_quantity' => 1,
                'product_price' => 25.00,
                'product_total_price' => 25.00,
                'item_type' => ItemType::DIGITAL,
            ]
        );

        // Real pathway: the same fulfillment service the payment listener
        // calls. Idempotent via UNIQUE(order_product_id).
        app(DigitalFulfillmentService::class)->fulfillOrder($order->fresh());

        $service = app(DigitalEntitlementService::class);
        $admin = User::where('email', env('DIGITAL_TEST_ADMIN_EMAIL', self::ADMIN_EMAIL))->first();

        // Finite limit + known usage.
        $entitlement = DigitalEntitlement::where('order_product_id', $item->id)->firstOrFail();
        $entitlement->forceFill(['download_limit' => 5, 'download_count' => 3])->save();
        $this->anchors['entitlement_uuid'] = $entitlement->uuid;

        // Expired entitlement (delivered + past expiry).
        $expired = DigitalEntitlement::where('order_product_id', $line2->id)->firstOrFail();
        $expired->forceFill([
            'status' => DigitalEntitlement::STATUS_DELIVERED,
            'delivered_at' => now()->subDays(10),
            'expires_at' => now()->subDay(),
        ])->save();
        $this->anchors['expired_entitlement_uuid'] = $expired->uuid;

        // Revoked entitlement (via the real service, like the endpoint).
        $revoked = DigitalEntitlement::where('order_product_id', $line3->id)->firstOrFail();
        $service->revoke($revoked->fresh(), $admin);
        $this->anchors['revoked_entitlement_uuid'] = $revoked->uuid;

        $this->anchors['product_id'] = (string) $product->id;
        $this->anchors['order_product_anchor'] = (string) $item->id;
    }

    /**
     * Minimal synthetic PDF: the W4 pipeline sniffs real bytes with finfo,
     * so the header must be a genuine PDF magic number. No real content.
     */
    private function syntheticPdf(): UploadedFile
    {
        $bytes = "%PDF-1.4\n" . str_repeat('%', 32 * 1024) . "\n%%EOF";
        $tmp = tempnam(sys_get_temp_dir(), 'digital-seed-') . '.pdf';
        file_put_contents($tmp, $bytes);

        return new UploadedFile($tmp, 'test-manual.pdf', 'application/pdf', null, true);
    }

    private function printSummary(User $admin): void
    {
        $this->command->info('Digital testing dataset ready (synthetic data only).');
        $this->command->table(
            ['key', 'value'],
            collect($this->anchors)->map(fn ($v, $k) => [$k, $v])->values()->all()
        );
        $this->command->info('Admin login: ' . $admin->email . ' (password from DIGITAL_TEST_ADMIN_PASSWORD env or the documented local default).');
        $this->command->warn('Local testing only. Never run this seeder against production.');
    }
}
